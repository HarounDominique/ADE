export function iconForFileName(name) {
  const lower = String(name ?? '').toLowerCase();
  if (byFileName[lower]) return byFileName[lower];
  // A source map's own extension is always .map; which map icon reads
  // right depends on what it maps, so the check looks one extension deeper.
  if (lower.endsWith('.css.map')) return 'css-map';
  const dot = lower.lastIndexOf('.');
  const ext = dot >= 0 ? lower.slice(dot + 1) : '';
  return byExtension[ext] ?? null;
}
